"""Vérifie les engagements communs sans générer de preuve ni envoyer de transaction."""
import json
import pathlib
import tomllib
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[1]
config = json.loads((ROOT / "integration.json").read_text())
rev = config["garaga_rev"]
assert config["sp1_groth16_image"] in (ROOT / "script/src/lib.rs").read_text()
assert config["sp1_build_image"] in (ROOT / "script/build.rs").read_text()
for name in ["contracts/Scarb.toml", "contracts/verifier/Scarb.toml"]:
    data = tomllib.loads((ROOT / name).read_text())
    deps = data.get("dependencies", {}) | data.get("dev-dependencies", {})
    assert deps["garaga"]["rev"] == rev, name
    assert deps["starknet"] == config["scarb"], name
    assert data["cairo"]["sierra-replace-ids"] is False, name
    assert data["cairo"]["inlining-strategy"] == 2, name
assert tomllib.loads((ROOT / "rust-toolchain").read_text())["toolchain"]["channel"] == config["rust"]
app = tomllib.loads((ROOT / "contracts/Scarb.toml").read_text())
assert app["dev-dependencies"]["snforge_std"] == config["snfoundry"]
script = tomllib.loads((ROOT / "script/Cargo.toml").read_text())
assert script["dependencies"]["garaga_rs"]["rev"] == rev
assert script["dependencies"]["sp1-sdk"]["version"] == "=" + config["sp1_sdk"]
assert script["build-dependencies"]["sp1-build"] == "=" + config["sp1_sdk"]
assert script["dev-dependencies"]["sp1-verifier"]["version"] == "=" + config["sp1_sdk"]
program = tomllib.loads((ROOT / "program/Cargo.toml").read_text())
assert program["dependencies"]["sp1-zkvm"] == "=" + config["sp1_sdk"]
source = "src/contracts/autogenerated/sp1_verifier_bn254/src/groth16_verifier.cairo"
url = f"https://raw.githubusercontent.com/keep-starknet-strange/garaga/{rev}/{source}"
with urllib.request.urlopen(url, timeout=60) as response:
    assert response.read() == (ROOT / "contracts/verifier/src/groth16_verifier.cairo").read_bytes(), "Vendored verifier differs from pinned Garaga"
print("Integration versions and upstream verifier match")
